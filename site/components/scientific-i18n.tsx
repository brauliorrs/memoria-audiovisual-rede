export type ScientificCopyKey = keyof typeof scientificCopy.pt;

export function useScientificCopy() {
  const {locale} = useSiteLocale();
  const copy: Record<ScientificCopyKey,string> = scientificCopy[locale];
  return copy;
}

export function ScientificText({id}:{id:ScientificCopyKey}) {
  const copy=useScientificCopy();
  return <>{copy[id]}</>;
}

export function ScientificNumber({value}:{value:number}) {
  const {locale}=useSiteLocale();
  const lang=locale==="pt"?"pt-BR":locale==="es"?"es-ES":"en-US";
  return <>{new Intl.NumberFormat(lang).format(value)}</>;
}

/** Localize UI geographic groups, not original source metadata or citations. */
export function localizeTerritory(value:string,locale:SiteLocale){
  const values:Record<string,Record<SiteLocale,string>>={
    "Europe":{pt:"Europa",en:"Europe",es:"Europa"},
    "North America":{pt:"América do Norte",en:"North America",es:"América del Norte"},
    "Nao classificado":{pt:"Não classificado",en:"Unclassified",es:"Sin clasificar"},
  };
  return values[value]?.[locale] ?? value;
}
